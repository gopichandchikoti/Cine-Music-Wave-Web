// Writes src/themes/motion.css: the three named springs as CSS `linear()` easings, plus the shared enter and exit
// keyframes. Run it again after changing a spring in src/utils/spring.ts.
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { SPRINGS, springEasing, type SpringName } from '../src/utils/spring.ts'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const names = Object.keys(SPRINGS) as SpringName[]

const tokens = names
  .map((name) => {
    const { easing, durationMs } = springEasing(SPRINGS[name])
    const { response, dampingFraction } = SPRINGS[name]
    return `  /* ${name}: response ${response}s, damping fraction ${dampingFraction} */\n  --spring-${name}: ${easing};\n  --spring-${name}-time: ${durationMs}ms;`
  })
  .join('\n')

const fallbacks = names.map((name) => `    --spring-${name}: cubic-bezier(0.2, 0.8, 0.2, 1);`).join('\n')

const css = `/*
 * Spring motion. Generated by scripts/generate-motion.ts from src/utils/spring.ts: do not edit the numbers by hand.
 *
 * Layout changes (a tab indicator moving, a menu or sheet opening, a player minimising) move on a damped spring, the
 * way iOS does, instead of a fixed-time curve. Only transform and opacity animate. Under reduced motion, travel and
 * scale stop and only a short fade remains.
 */

:root {
${tokens}
}

@supports not (transition-timing-function: linear(0, 1)) {
  :root {
${fallbacks}
  }
}

@keyframes spring-fade-in { from { opacity: 0; } to { opacity: 1; } }
@keyframes spring-fade-out { from { opacity: 1; } to { opacity: 0; } }
@keyframes spring-pop-in { from { opacity: 0; transform: scale(0.9) translateY(-6px); } to { opacity: 1; transform: none; } }
@keyframes spring-pop-out { from { opacity: 1; transform: none; } to { opacity: 0; transform: scale(0.94) translateY(-4px); } }
@keyframes spring-rise-in { from { opacity: 0; transform: translateY(24px) scale(0.97); } to { opacity: 1; transform: none; } }
@keyframes spring-rise-out { from { opacity: 1; transform: none; } to { opacity: 0; transform: translateY(20px) scale(0.98); } }
@keyframes spring-sheet-in { from { transform: translateY(100%); } to { transform: none; } }
@keyframes spring-sheet-out { from { transform: none; } to { transform: translateY(100%); } }
@keyframes spring-expand-in { from { opacity: 0.6; transform: translateY(6%) scale(0.96); } to { opacity: 1; transform: none; } }
@keyframes spring-expand-out { from { opacity: 1; transform: none; } to { opacity: 0; transform: translateY(8%) scale(0.95); } }

/* The element that keeps an overlay mounted while it leaves (see components/Presence). It adds no box of its own. */
.presence { display: contents; }

/* A sliding highlight behind the active tab (see hooks/useSlidingIndicator). */
[data-indicator] { position: relative; isolation: isolate; }
[data-indicator] > * { position: relative; z-index: 1; }
[data-indicator]::after {
  content: '';
  position: absolute;
  z-index: 0;
  top: 0;
  left: 0;
  width: var(--indicator-width, 0);
  height: var(--indicator-height, 0);
  transform: translate(var(--indicator-x, 0), var(--indicator-y, 0));
  pointer-events: none;
}
[data-indicator='ready']::after {
  transition:
    transform var(--spring-snappy-time) var(--spring-snappy),
    width var(--spring-snappy-time) var(--spring-snappy),
    height var(--spring-snappy-time) var(--spring-snappy);
}

@media (prefers-reduced-motion: reduce) {
  [data-indicator='ready']::after { transition: none; }
  @keyframes spring-pop-in { from { opacity: 0; } to { opacity: 1; } }
  @keyframes spring-pop-out { from { opacity: 1; } to { opacity: 0; } }
  @keyframes spring-rise-in { from { opacity: 0; } to { opacity: 1; } }
  @keyframes spring-rise-out { from { opacity: 1; } to { opacity: 0; } }
  @keyframes spring-sheet-in { from { opacity: 0; } to { opacity: 1; } }
  @keyframes spring-sheet-out { from { opacity: 1; } to { opacity: 0; } }
  @keyframes spring-expand-in { from { opacity: 0; } to { opacity: 1; } }
  @keyframes spring-expand-out { from { opacity: 1; } to { opacity: 0; } }
}
`

writeFileSync(path.join(root, 'src/themes/motion.css'), css)
process.stdout.write(
  `motion.css written: ${names.map((name) => `${name} ${springEasing(SPRINGS[name]).durationMs}ms`).join(', ')}\n`,
)
